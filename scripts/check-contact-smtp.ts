import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { contactMail, createSmtpContactHandler, smtpContactConfigured, type SmtpContactEnv } from "../server/contact-smtp.ts";

const now = Date.now();
const origin = "https://preview.example";
const env: SmtpContactEnv = { VERCEL: "1", VERCEL_ENV: "preview", CONTACT_ENABLED: "true", CONTACT_SMTP_HOST: "mail.juliefleur.nl", CONTACT_SMTP_PORT: "465", CONTACT_SMTP_USER: "info@juliefleur.nl", CONTACT_SMTP_PASSWORD: "mock-only" };
const payload = { name: "Testpersoon", email: "bezoeker@example.org", subject: "Test personaliseren", message: "Dit is een gesimuleerde test zonder echte verzending.", website: "", startedAt: now - 5000, submissionId: randomUUID() };
const request = (body: unknown = payload, extra: Record<string, string> = {}) => new Request(`${origin}/api/contact`, { method: "POST", headers: { origin, "Content-Type": "application/json", "x-vercel-forwarded-for": "192.0.2.5", ...extra }, body: JSON.stringify(body) });
let sends = 0;
const handler = createSmtpContactHandler({ sendMail: async () => { sends++; return true; }, now: () => now });
let count = 0;
async function status(req: Request, expected: number, configuration = env) {
  const response = await handler(req, configuration);
  assert.equal(response.status, expected);
  count++;
  return response;
}
assert.equal(smtpContactConfigured(env), true);
assert.equal(smtpContactConfigured({ ...env, CONTACT_SMTP_PASSWORD: "" }), false);
assert.equal(smtpContactConfigured({ ...env, CONTACT_SMTP_PORT: "25" }), false);
assert.equal(smtpContactConfigured({ ...env, CONTACT_SMTP_HOST: "attacker.example" }), false);
assert.equal(smtpContactConfigured({ ...env, CONTACT_SMTP_USER: "other@example.org" }), false);
assert.equal(smtpContactConfigured({ ...env, VERCEL_ENV: "production" }), false);
assert.equal(smtpContactConfigured({ ...env, VERCEL_ENV: "production", CONTACT_DELIVERY_VERIFIED: "true" }), true);
assert.equal(smtpContactConfigured({ ...env, VERCEL: "" }), false);
const unavailable = await status(new Request(`${origin}/api/contact`), 200, {});
assert.deepEqual(await unavailable.json(), { ready: false });
const available = await status(new Request(`${origin}/api/contact`), 200);
assert.deepEqual(await available.json(), { ready: true });
await status(request(), 503, {});
await status(request(payload, { origin: "https://attacker.example" }), 403);
await status(request(payload, { "sec-fetch-site": "cross-site" }), 403);
await status(request(payload, { "Content-Type": "text/plain" }), 415);
await status(request(null), 422);
await status(request({ ...payload, name: "Naam\nBcc: test@example.org" }), 422);
await status(request({ ...payload, email: "naam@example.org\r\nBcc: test@example.org" }), 422);
await status(request({ ...payload, subject: "Onderwerp\nTweede regel" }), 422);
await status(request({ ...payload, message: "kort" }), 422);
await status(request({ ...payload, message: "a".repeat(40000) }), 413);
await status(request({ ...payload, website: "https://bot.example" }), 400);
await status(request({ ...payload, startedAt: now - 100 }), 400);
await status(request({ ...payload, startedAt: now - 86400001 }), 400);
await status(request({ ...payload, submissionId: "bad" }), 400);
await status(request(payload, { "x-vercel-forwarded-for": "" }), 503);
await status(request(payload, { "x-vercel-forwarded-for": "spoof, 192.0.2.5" }), 503);
assert.equal(sends, 0);
const response = await status(request({ ...payload, to: "attacker@example.org" }), 200);
assert.deepEqual(await response.json(), { ok: true, reference: payload.submissionId });
await status(request(), 200);
assert.equal(sends, 1, "Dubbelklik binnen dezelfde instantie verstuurt één keer");
await status(request({ ...payload, message: "Een ander bericht met hetzelfde berichtkenmerk." }), 409);
await status(request({ ...payload, submissionId: randomUUID() }), 200);
await status(request({ ...payload, submissionId: randomUUID() }), 200);
const limited = await status(request({ ...payload, submissionId: randomUUID() }), 429);
assert.equal(limited.headers.get("Retry-After"), "900");
const failed = createSmtpContactHandler({ sendMail: async () => { throw new Error("Simulated SMTP outage"); }, now: () => now });
assert.equal((await failed(request(), env)).status, 502); count++;
const rejected = createSmtpContactHandler({ sendMail: async () => false, now: () => now });
assert.equal((await rejected(request(), env)).status, 502); count++;
await status(new Request(`${origin}/api/contact`, { method: "PUT" }), 405);
const email = contactMail({ fields: payload, reference: payload.submissionId });
assert.equal(email.from.address, "info@juliefleur.nl");
assert.equal(email.to, "info@juliefleur.nl");
assert.equal(email.replyTo.address, payload.email);
assert.match(email.text, /Testpersoon/);
assert.equal(email.disableFileAccess, true);
assert.equal(email.disableUrlAccess, true);
assert.equal(response.headers.get("Cache-Control"), "no-store");
console.log(`SMTP-contactcontrole geslaagd: ${count} endpointscenario’s; configuratie, vaste ontvanger, Reply-To, invoer, spamcontrole, begrenzing, dubbelklik en SMTP-storing. Geen echte mail verstuurd.`);
